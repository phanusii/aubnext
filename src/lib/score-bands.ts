// สุ่มข้อความแบบคงที่ต่อคน (seed) — มิเรอร์ pickText เดิมใน DevelopmentStatsPanel
function pickBandText(options: string[], seed: number) {
  return options[Math.abs(Math.round(seed)) % options.length] ?? options[0] ?? "";
}

export function totalBandAdvice(band: ScoreBand, seed: number): string {
  return pickBandText(TOTAL_ADVICE_BY_BAND[band.index], seed);
}

export function subjectBandAdvice(
  band: ScoreBand,
  subjectName: string,
  gap: number,
  nextLabel: string | null,
  seed: number,
): string {
  const template = pickBandText(SUBJECT_ADVICE_BY_BAND[band.index], seed);
  return template
    .replaceAll("{subject}", subjectName)
    .replaceAll("{gap}", Number.isFinite(gap) ? formatBandPoints(gap) : "เล็กน้อย")
    .replaceAll("{nextLabel}", nextLabel ?? "ถัดไป");
}

function formatBandPoints(value: number) {
  const abs = Math.abs(value);
  return Number.isInteger(abs) ? String(abs) : abs.toFixed(1);
}
