// โมเดล "10 ช่วงคะแนน" แบบ decile (% ของคะแนนเต็ม) + คลังคำแนะนำเพื่อการพัฒนา
// ใช้กับทั้งคะแนนรวมและรายวิชา เพื่อให้คำแนะนำตรงตามระดับคะแนนสัมบูรณ์ของนักเรียน
// (ใช้ผสมกับบริบทอันดับเทียบเพื่อนใน DevelopmentStatsPanel)

export type ScoreBandTone = "rose" | "amber" | "sky" | "emerald";

export type ScoreBand = {
  index: number; // 0 (ต่ำสุด) .. 9 (สูงสุด) = floor(pct/10)
  label: string; // ชื่อช่วง เช่น "ดีมาก"
  rangeLabel: string; // เช่น "80–89%"
  tone: ScoreBandTone;
  pct: number; // เปอร์เซ็นต์จริง (0–100)
};

// ชื่อช่วง เรียงจากต่ำ (index 0) ไปสูง (index 9)
const BAND_LABELS = [
  "เริ่มปูพื้นฐาน", // 0–9%
  "ปูพื้นฐาน", // 10–19%
  "กำลังตั้งต้น", // 20–29%
  "ต้องเร่งพัฒนา", // 30–39%
  "ใกล้เกณฑ์", // 40–49%
  "ผ่านเกณฑ์", // 50–59%
  "พอใช้ถึงดี", // 60–69%
  "ดี", // 70–79%
  "ดีมาก", // 80–89%
  "ยอดเยี่ยม", // 90–100%
] as const;

function bandTone(index: number): ScoreBandTone {
  if (index <= 3) return "rose";
  if (index <= 5) return "amber";
  if (index <= 7) return "sky";
  return "emerald";
}

/** คืนช่วงคะแนน (decile) จากคะแนนและคะแนนเต็ม — คืน null ถ้าไม่มีคะแนนเต็ม (คิด % ไม่ได้) */
export function scoreBand(score: number, max: number | undefined | null): ScoreBand | null {
  if (!Number.isFinite(score) || !Number.isFinite(max ?? NaN) || (max ?? 0) <= 0) return null;
  const pct = Math.max(0, Math.min(100, (score / (max as number)) * 100));
  const index = Math.max(0, Math.min(9, Math.floor(pct / 10)));
  const low = index * 10;
  const high = index === 9 ? 100 : index * 10 + 9;
  return { index, label: BAND_LABELS[index], rangeLabel: `${low}–${high}%`, tone: bandTone(index), pct };
}

/** คะแนนที่ต้องเพิ่มเพื่อขยับขึ้นช่วงถัดไป — คืน null ถ้าอยู่ช่วงสูงสุดแล้ว */
export function pointsToNextBand(
  score: number,
  max: number | undefined | null,
): { points: number; nextLabel: string } | null {
  const band = scoreBand(score, max);
  if (!band || band.index >= 9) return null;
  const nextScore = (((band.index + 1) * 10) / 100) * (max as number);
  return { points: Math.max(0, nextScore - score), nextLabel: BAND_LABELS[band.index + 1] };
}

